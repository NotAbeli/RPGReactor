/*:ru
 * @target MV MZ
 * @plugindesc Позволяет задать прозрачность и реальный сдвиг (Offset) события через примечание.
 * @author Gemini AI
 *
 * @help
 * ============================================================================
 * Описание
 * ============================================================================
 * Этот плагин позволяет настраивать свойства событий через теги в поле
 * "Примечание" (Note).
 *
 * ОТЛИЧИЕ ОТ ВЕРСИИ 1.1:
 * - Улучшена совместимость с физическими движками (Altimit).
 * - Добавлен тег <through:true> для отключения выталкивания из стен.
 *
 * ============================================================================
 * Теги (Вставлять в поле Note события)
 * ============================================================================
 *
 * 1. Прозрачность:
 * <opacity:X>
 * Где X — число от 0 до 100.
 * Пример: <opacity:50>
 *
 * 2. Сдвиг по горизонтали (X) в пикселях:
 * <offsetX:X>
 * Пример: <offsetX:24>
 *
 * 3. Сдвиг по вертикали (Y) в пикселях:
 * <offsetY:Y>
 * Пример: <offsetY:-10>
 *
 * 4. Отключение коллизии (Проходимость):
 * <through:true>
 * Добавьте этот тег, если событие "прыгает" обратно на сетку.
 * Это происходит, если сдвиг помещает событие внутрь стены, и физический
 * движок выталкивает его наружу. Этот тег разрешает событию быть в стене.
 *
 * ============================================================================
 * Важно для Altimit Movement / Pixel Movement
 * ============================================================================
 * Если событие сдвигается и тут же возвращается обратно:
 * Значит, оно задевает "непроходимый" тайл.
 * Решение:
 * А) Сделайте смещение меньше, чтобы не задевать стену.
 * Б) Или используйте тег <through:true>, чтобы отключить физику для этого
 * конкретного события (оно станет декорацией, сквозь которую можно пройти).
 */

(function() {
    'use strict';

    // -----------------------------------------------------------------------
    // Game_Event
    // -----------------------------------------------------------------------

    // Перехватываем установку начальной позиции события
    var _Game_Event_locate = Game_Event.prototype.locate;
    Game_Event.prototype.locate = function(x, y) {
        var data = this.event();
        
        var offX = 0;
        var offY = 0;

        if (data && data.meta) {
            var tw = $gameMap.tileWidth();
            var th = $gameMap.tileHeight();

            // Считаем сдвиги
            if (data.meta.offsetX) {
                offX = Number(data.meta.offsetX) / tw; 
            }
            if (data.meta.offsetY) {
                offY = Number(data.meta.offsetY) / th;
            }
        }

        // Применяем сдвиг к аргументам
        var newX = x + offX;
        var newY = y + offY;

        // Вызываем оригинальную функцию (инициализация физики Altimit происходит тут)
        _Game_Event_locate.call(this, newX, newY);

        // ДОПОЛНИТЕЛЬНАЯ ЗАЩИТА:
        // Некоторые плагины могут игнорировать аргументы и брать this.event().x
        // Поэтому мы принудительно перезаписываем координаты после инициализации.
        if (offX !== 0 || offY !== 0) {
            this._x = newX;
            this._y = newY;
            this._realX = newX;
            this._realY = newY;
        }
    };

    // Настройка свойств страницы (Прозрачность и Проходимость)
    var _Game_Event_setupPage = Game_Event.prototype.setupPage;
    Game_Event.prototype.setupPage = function() {
        _Game_Event_setupPage.call(this);
        this.setupCustomProps();
    };

    Game_Event.prototype.setupCustomProps = function() {
        var data = this.event();
        if (!data || !data.meta) return;

        // --- 1. Прозрачность ---
        if (data.meta.opacity !== undefined) {
            var percent = Number(data.meta.opacity);
            percent = Math.max(0, Math.min(100, percent));
            this.setOpacity(Math.round(255 * (percent / 100)));
        }

        // --- 2. Проходимость (Through) ---
        // Если событие "выталкивается" из стен, этот тег поможет
        if (data.meta.through && String(data.meta.through).trim() === 'true') {
            this.setThrough(true);
            this.setPriorityType(0); // Обычно 'through' события находятся под игроком, но это опционально
        }
    };

})();